'use strict';
const fs=require('fs'),path=require('path');
const R=path.resolve(__dirname,'../..');
const read=f=>fs.readFileSync(path.join(R,f),'utf8');
const exists=f=>fs.existsSync(path.join(R,f));
const strip=p=>p.split('?')[0].replace(/^\.\//,'');
const h=read('index.html'),sw=read('service-worker.js'),manifest=JSON.parse(read('manifest.webmanifest')),map=JSON.parse(read('config/runtime-map.json'));
const startup=[...h.matchAll(/<script[^>]+src=["']([^"']+)["']/g)].map(x=>strip(x[1]));
const styles=[...h.matchAll(/<link[^>]+rel=["']stylesheet["'][^>]+href=["']([^"']+)["']/g)].map(x=>strip(x[1]));
