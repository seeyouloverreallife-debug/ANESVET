add('Service Worker precaches all runtime-map icons',cfgIcons.every(x=>swPaths.has(x)));
add('No old root production CSS path remains in index or SW',!h.includes('./anesvet-ui-bundle.css')&&!h.includes('./or-workspace-restructure.css')&&!sw.includes('./anesvet-ui-bundle.css')&&!sw.includes('./or-workspace-restructure.css'));
