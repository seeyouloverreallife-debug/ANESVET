const cfgStartup=map.startupModules.slice().sort((a,b)=>a.order-b.order).map(x=>x.path);
const cfgLazy=map.lazyModules.map(x=>x.path);
const cfgStyles=map.styles.map(x=>x.path);
const cfgIcons=map.icons.map(x=>x.path);
const allModules=[...cfgStartup,...cfgLazy];
const dup=a=>[...new Set(a.filter((x,i)=>a.indexOf(x)!==i))];
const validGroups=new Set([...Object.keys(map.groups),...Object.keys(map.futureGroups||{})]);
const knowledge=read('knowledge-loader.js');
const knowledgeFiles=[...knowledge.matchAll(/'([^']+\.js)'/g)].map(x=>x[1]).filter(x=>cfgLazy.includes(x));
const iconRefs=[...h.matchAll(/(?:href|src)=["'](\.\/assets\/icons\/[^"']+)["']/g)].map(x=>strip(x[1]));
const manifestIcons=(manifest.icons||[]).map(x=>strip(x.src));
const retired=['ui-refinement.js','adaptive-workspace.js','clinical-simplicity.js','recovery-endcase-ux.js','repeat-use-ux.js','repeat-use-r26.js','focused-workspace.js','progressive-disclosure.js','progressive-clinical-flow.js','pilot-efficiency.js','usability-hardening.js','mobile-first-r27.js','or-speed-hardening.js'];
