add('Runtime map startup order exactly matches index.html',JSON.stringify(cfgStartup)===JSON.stringify(startup));
add('Every startup module path exists',cfgStartup.every(exists));
add('Every lazy module path exists',cfgLazy.every(exists));
add('Startup JS stays at root in preparation release',cfgStartup.every(x=>!x.includes('/')));
add('Lazy JS is grouped under runtime/knowledge',cfgLazy.every(x=>x.startsWith('runtime/knowledge/')));
add('No lazy knowledge module remains at root',cfgLazy.every(x=>!exists(x.split('/').pop())));
add('Lazy current paths equal migration target paths',map.lazyModules.every(x=>x.path===x.futurePath));
add('Every startup module has a valid ownership group',map.startupModules.every(x=>validGroups.has(x.group)));
add('Every future startup path targets runtime/*',map.startupModules.every(x=>/^runtime\//.test(x.futurePath)));
add('Every future lazy path targets runtime/knowledge/*',map.lazyModules.every(x=>/^runtime\/knowledge\//.test(x.futurePath)));
add('Service Worker precaches all startup modules',cfgStartup.every(x=>swPaths.has(x)));
add('Service Worker precaches all lazy modules',cfgLazy.every(x=>swPaths.has(x)));
