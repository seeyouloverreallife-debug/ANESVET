'use strict';
const fs=require('fs'),path=require('path'),R=path.resolve(__dirname,'../..');
const exists=p=>fs.existsSync(path.join(R,p));
const files=(p,rx)=>fs.readdirSync(path.join(R,p),{withFileTypes:true}).filter(x=>x.isFile()&&(!rx||rx.test(x.name))).map(x=>x.name);
const rootFiles=files('.');
const archivedQA=files('qa/archive');
const currentQA=files('qa/current',/\.js$/);
const releaseDocs=files('docs/releases',/^RELEASE_.*\.md$/);
const ownerDocs=files('docs/architecture',/^OWNER_MAP_.*\.md$/);
const auditDocs=files('docs/audits',/\.md$/);
const retirementDocs=files('docs/retirement',/\.md$/);
const canonicalCss=files('src/styles/canonical',/\.css$/);
const legacyCss=files('src/styles/legacy-active',/\.css$/);
const legacyJs=files('src/legacy-js',/\.js$/);
const T=[];const add=(n,v)=>T.push([n,!!v]);
add('Package has docs/releases folder',exists('docs/releases'));
add('Package has docs/architecture folder',exists('docs/architecture'));
add('Package has docs/audits folder',exists('docs/audits'));
add('Package has docs/retirement folder',exists('docs/retirement'));
add('Package has qa/current and qa/archive folders',exists('qa/current')&&exists('qa/archive'));
add('Package has qa/evidence folder',exists('qa/evidence'));
add('Package has src/styles/canonical and legacy-active folders',exists('src/styles/canonical')&&exists('src/styles/legacy-active'));
add('Package has src/legacy-js folder',exists('src/legacy-js'));
add('Package has build/history folder',exists('build/history'));
add('Root file count reduced below 100',rootFiles.length<100);
add('No RELEASE markdown remains at root',!rootFiles.some(x=>/^RELEASE_.*\.md$/.test(x)));
add('No OWNER_MAP markdown remains at root',!rootFiles.some(x=>/^OWNER_MAP_.*\.md$/.test(x)));
add('No QA scripts/results remain at root',!rootFiles.some(x=>/^QA_/.test(x)));
add('Historical release notes preserved',releaseDocs.length>=40);
add('Owner-map history preserved',ownerDocs.length>=8);
add('Audit documents grouped',auditDocs.length>=4);
add('Retirement history grouped',retirementDocs.length>=9);
add('Historical QA preserved in archive',archivedQA.length>=90);
add('Current QA suite contains six scripts',currentQA.length===6);
add('Canonical bundle source CSS count is 29',canonicalCss.length===29);
add('Legacy-active bundle source CSS count is 9',legacyCss.length===9);
add('Retired JS archive contains 13 owners',legacyJs.length===13);
add('Old build metadata moved to build/history',exists('build/history/BUILD_SHA256_V17_6_3.txt')&&exists('build/history/SOURCE_SHA256.json'));
add('Current BUILD_SHA256 remains at package root',exists('BUILD_SHA256.txt'));
add('START_HERE remains at package root',exists('START_HERE_TH.txt'));
add('Runtime entrypoints remain at root',exists('index.html')&&exists('service-worker.js')&&exists('manifest.webmanifest')&&exists('app.js'));
let p=0;for(const [n,v] of T){console.log((v?'PASS':'FAIL')+'  '+n);if(v)p++;}
console.log(`\n${p}/${T.length} PASS`);process.exit(p===T.length?0:1);
